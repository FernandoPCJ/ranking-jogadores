-- =========================================================
-- HISTÓRICO DE SORTEIOS DE TIMES
-- Ranking de Jogadores
--
-- - Todo sorteio feito pelo admin fica registrado com data,
--   horário (do servidor, não do navegador), quem sorteou e
--   os times formados.
-- - Limite: no máximo 1 sorteio a cada 15 minutos (global).
-- - O histórico não pode ser editado nem apagado pelo app:
--   a tabela não tem policies de escrita e só é alimentada
--   pela RPC registrar_sorteio().
-- - Qualquer usuário logado pode consultar o histórico.
-- =========================================================


-- =========================================================
-- 1. TABELA
-- =========================================================

create table if not exists public.sorteios (
  id               bigint generated by default as identity primary key,
  realizado_em     timestamptz not null default now(),
  realizado_por    uuid        not null references auth.users(id),
  quantidade_times integer     not null,
  diferenca        integer     not null,
  times            jsonb       not null,
  constraint sorteios_quantidade_times_valida
    check (quantidade_times in (3, 4))
);

create index if not exists sorteios_realizado_em_idx
  on public.sorteios (realizado_em desc);

alter table public.sorteios
  enable row level security;

-- Nenhuma policy: ninguém lê ou escreve direto na tabela.
-- Leitura e escrita passam apenas pelas RPCs abaixo.
revoke all on public.sorteios from anon, authenticated;


-- =========================================================
-- 2. REGISTRAR SORTEIO (somente admin, 1 a cada 15 min)
--
-- p_times: [[id, id, ...], [id, id, ...], ...]
-- As estrelas são lidas do banco, não do navegador.
-- =========================================================

create or replace function public.registrar_sorteio(
  p_times jsonb
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_intervalo constant interval := interval '15 minutes';
  v_ultimo timestamptz;
  v_qtd_times integer;
  v_tamanho_esperado integer;
  v_total_ids integer;
  v_ids_distintos integer;
  v_ids_validos integer;
  v_times jsonb;
  v_diferenca integer;
  v_registro public.sorteios;
begin
  if not exists (
    select 1
    from public.perfis
    where id = auth.uid()
      and tipo = 'admin'
  ) then
    raise exception
      'Apenas administradores podem sortear times.';
  end if;

  -- Impede dois sorteios simultâneos burlando o limite.
  perform pg_advisory_xact_lock(
    hashtext('public.registrar_sorteio')
  );

  select max(realizado_em)
  into v_ultimo
  from public.sorteios;

  if
    v_ultimo is not null
    and now() < v_ultimo + v_intervalo
  then
    raise exception
      'Aguarde até % para sortear novamente.',
      to_char(
        (v_ultimo + v_intervalo)
          at time zone 'America/Fortaleza',
        'HH24:MI'
      )
      using errcode = 'P0001',
            hint = 'LIMITE_SORTEIO';
  end if;

  if
    p_times is null
    or jsonb_typeof(p_times) <> 'array'
  then
    raise exception 'Formato de times inválido.';
  end if;

  v_qtd_times := jsonb_array_length(p_times);

  if v_qtd_times not in (3, 4) then
    raise exception 'O sorteio deve ter 3 ou 4 times.';
  end if;

  v_tamanho_esperado :=
    case when v_qtd_times = 3 then 12 else 16 end;

  select
    count(*),
    count(distinct ids.id)
  into
    v_total_ids,
    v_ids_distintos
  from jsonb_array_elements(p_times) as t(time_json)
  cross join lateral (
    select (value)::bigint as id
    from jsonb_array_elements_text(t.time_json)
  ) as ids;

  if
    v_total_ids <> v_tamanho_esperado
    or v_ids_distintos <> v_total_ids
  then
    raise exception
      'O sorteio precisa de exatamente % jogadores diferentes.',
      v_tamanho_esperado;
  end if;

  select count(*)
  into v_ids_validos
  from public.jogadores j
  where j.ativo = true
    and j.id in (
      select (value)::bigint
      from jsonb_array_elements(p_times) as t(time_json),
           jsonb_array_elements_text(t.time_json)
    );

  if v_ids_validos <> v_total_ids then
    raise exception
      'O sorteio contém jogadores inválidos ou inativos.';
  end if;

  -- Monta o retrato do sorteio com nomes e estrelas do momento.
  select jsonb_agg(
    jsonb_build_object(
      'numero', x.numero,
      'total_estrelas', x.total_estrelas,
      'jogadores', x.jogadores
    )
    order by x.numero
  )
  into v_times
  from (
    select
      t.numero::integer as numero,
      sum(j.estrelas)::integer as total_estrelas,
      jsonb_agg(
        jsonb_build_object(
          'id', j.id,
          'nome', j.nome,
          'apelido', p.apelido,
          'estrelas', j.estrelas
        )
        order by j.estrelas desc, coalesce(p.apelido, j.nome)
      ) as jogadores
    from jsonb_array_elements(p_times)
      with ordinality as t(time_json, numero)
    cross join lateral
      jsonb_array_elements_text(t.time_json) as e(id_texto)
    join public.jogadores j
      on j.id = e.id_texto::bigint
    left join public.perfis p
      on p.jogador_id = j.id
    group by t.numero
  ) x;

  select
    max((value ->> 'total_estrelas')::integer)
    - min((value ->> 'total_estrelas')::integer)
  into v_diferenca
  from jsonb_array_elements(v_times);

  insert into public.sorteios (
    realizado_por,
    quantidade_times,
    diferenca,
    times
  )
  values (
    auth.uid(),
    v_qtd_times,
    v_diferenca,
    v_times
  )
  returning * into v_registro;

  return jsonb_build_object(
    'id', v_registro.id,
    'realizado_em', v_registro.realizado_em,
    'proximo_liberado_em',
      v_registro.realizado_em + v_intervalo,
    'quantidade_times', v_registro.quantidade_times,
    'diferenca', v_registro.diferenca,
    'times', v_registro.times
  );
end;
$$;

revoke all
on function public.registrar_sorteio(jsonb)
from public, anon;

grant execute
on function public.registrar_sorteio(jsonb)
to authenticated;


-- =========================================================
-- 3. LISTAR HISTÓRICO (qualquer usuário logado)
-- =========================================================

create or replace function public.listar_sorteios(
  p_limite integer default 20
)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'agora', now(),
    'proximo_liberado_em', (
      select max(realizado_em) + interval '15 minutes'
      from public.sorteios
    ),
    'sorteios', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', s.id,
          'realizado_em', s.realizado_em,
          'realizado_por', coalesce(p.nome, 'Administrador'),
          'quantidade_times', s.quantidade_times,
          'diferenca', s.diferenca,
          'times', s.times
        )
        order by s.realizado_em desc
      )
      from (
        select *
        from public.sorteios
        order by realizado_em desc
        limit least(greatest(coalesce(p_limite, 20), 1), 100)
      ) s
      left join public.perfis p
        on p.id = s.realizado_por
    ), '[]'::jsonb)
  );
$$;

revoke all
on function public.listar_sorteios(integer)
from public, anon;

grant execute
on function public.listar_sorteios(integer)
to authenticated;
